def write_yaml(path, value, guide_version=None):
    path.parent.mkdir(parents=True, exist_ok=True)
    text = yaml.safe_dump(value, sort_keys=False, allow_unicode=True, width=110)
    if guide_version:
        text = text.replace("/nrg-planner/guide.html", "/nrg-planner/guide.html?v=" + guide_version)
    path.write_text("# Generated by tools/build_ui.py.\n" + text)


