def price_generator(kind):
    return f"const kind = '{kind}';\n" + """const p = entity?.attributes?.plan;
if (!p || p.expires_at * 1000 <= Date.now()) return [];
const rows = Array.isArray(p.slots) ? p.slots : [], h = p.household || {}, points = [];
function emit(time, value) {
  if (points.length && points[points.length-1][0] === time) points[points.length-1][1] = value;
  else points.push([time,value]);
}
for (const s of rows) {
  const a = Math.max(start.getTime(), s.start * 1000), b = Math.min(end.getTime(), s.end * 1000);
  const rate = s.display_import_price === undefined ? s.import_price : s.display_import_price;
  if (b <= a || !Number.isFinite(rate)) continue;
  emit(a,null);
  const matches = kind === 'live' ? ['flat','running_average','time_of_use','external_live'].includes(s.price_source)
    : kind === 'forecast' ? ['day_ahead','external_forecast'].includes(s.price_source)
     : kind === 'estimate' ? s.price_source === 'recorded_estimate' : Number.isFinite(h.best_start) && Number.isFinite(h.best_end);
  let left = a, right = b;
  if (kind === 'suggested') { left = Math.max(a, h.best_start * 1000); right = Math.min(b, h.best_end * 1000); }
  if (matches && right > left) { emit(left,rate*100); emit(right-1,rate*100); emit(right,null); }
  emit(b,null);
}
return points;"""


