def grid(cards, columns=2):
    return {"type": "grid", "columns": columns, "square": False, "cards": cards}


def section(cards):
    return {"type": "grid", "cards": [{**card, "grid_options": {"columns": "full", **card.get("grid_options",{})}} for card in cards]}


def view(title, path, sections, **extra):
    return {"title": title, "path": path, "type": "sections", "max_columns": 2, "sections": [section(cards) for cards in sections], **extra}


def heading(title):
    return {"type": "heading", "heading": title, "heading_style": "title"}


def settings_view(title, path, sections):
    """Keep reading order and content-sized, full-width cards on every screen."""
    result = view(title, path, sections, dense_section_placement=False)
    for group in result["sections"]:
        for card in group["cards"]:
            card["grid_options"].setdefault("rows", "auto")
    return result


